from __future__ import annotations

from typing import Dict, Tuple

import runtime_archive
import runtime_csharp
import runtime_mongo
import runtime_tenant
from naming import GEN_DIR, custom_file, header, member, method_name, repo_class
from schema import Table, index_specs, methods_of, tenant_column

L = "csharp"

CS_TYPE = {"uuid": "Guid", "string": "string", "text": "string", "int": "int", "bigint": "long",
           "decimal": "decimal", "bool": "bool", "date": "DateOnly", "datetime": "DateTimeOffset", "json": "string"}
REF_TYPES = {"string", "text", "json"}


def _prop_type(c) -> str:
    t = CS_TYPE[c.type]
    return t + "?" if c.nullable else t


def _lit(c) -> str:
    v = c.default
    if isinstance(v, bool):
        return "true" if v else "false"
    if c.type in ("string", "text"):
        return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'
    if c.type == "decimal":
        return f"{v}m"
    if c.type == "bigint":
        return f"{v}L"
    return str(v)


def _table_file(t: Table, tables: Dict[str, Table], schema_rel: str, ns: str, dialect: str) -> str:
    pk = t.pk
    pkt = CS_TYPE[pk.type]
    repo = repo_class(L, t.name)
    out = []
    w = out.append
    w(header(L, schema_rel) + "// <auto-generated />")
    w("#nullable enable")
    w("using System;")
    w("using System.Collections.Generic;")
    w("using System.ComponentModel.DataAnnotations;")
    w("using System.ComponentModel.DataAnnotations.Schema;")
    w("using System.Linq;")
    w("using System.Threading;")
    w("using System.Threading.Tasks;")
    w("using Microsoft.EntityFrameworkCore;\n")
    w(f"namespace {ns};\n")
    w(f"/// <summary>{t.name}: entità della tabella {t.db_name}.{(' ' + t.description) if t.description else ''}</summary>")
    w(f'[Table("{t.db_name}")]')
    for s in index_specs(t):
        cols = ", ".join(f"nameof({c})" for c in s.columns)
        uq = ", IsUnique = true" if s.unique else ""
        w(f'[Index({cols}, Name = "{s.name}"{uq})]')
    w(f"public partial class {t.name}")
    w("{")
    for c in t.columns:
        attrs = []
        if c.primary_key:
            attrs.append("Key")
            if c.auto and c.type in ("int", "bigint"):
                attrs.append("DatabaseGenerated(DatabaseGeneratedOption.Identity)")
            elif not c.auto:
                attrs.append("DatabaseGenerated(DatabaseGeneratedOption.None)")
            # Guid automatico: lo genera EF all'inserimento (Guid.Empty = record nuovo)
        attrs.append(f'Column("{c.db_name}"' + (f', TypeName = "jsonb"' if c.type == "json" and dialect == "postgres" else "") + ")")
        if c.required and c.type in REF_TYPES:
            attrs.append("Required")
        if c.type == "string":
            attrs.append(f"MaxLength({c.length})")
        if c.type == "decimal":
            attrs.append(f"Precision({c.precision}, {c.scale})")
        w(f"    [{', '.join(attrs)}]")
        init = ""
        if c.default is not None:
            init = f" = {_lit(c)};"
        elif not c.nullable and c.type in REF_TYPES:
            init = " = null!;"
        w(f"    public {_prop_type(c)} {c.name} {{ get; set; }}{init}\n")
    for r in t.relations:
        if r.kind == "many_to_one":
            nul = "?" if t.col(r.foreign_key).nullable else ""
            init = "" if nul else " = null!;"
            w(f"    [ForeignKey(nameof({r.foreign_key}))]")
            w(f"    public {r.target}{nul} {r.name} {{ get; set; }}{init}\n")
        else:
            w(f"    public ICollection<{r.target}> {r.name} {{ get; set; }} = new List<{r.target}>();\n")
    out[-1] = out[-1].rstrip("\n")
    w("}\n")

    # ---- validazione
    w(f"/// <summary>Validazione di modello prima della persistenza.</summary>")
    w(f"public static partial class {t.name}Validation")
    w("{")
    w(f"    public static void Validate({t.name} e)")
    w("    {")
    w("        var errors = new Dictionary<string, string>();")
    for c in t.columns:
        if c.required and c.type in REF_TYPES and not c.generated and not c.tenant:
            w(f'        if (e.{c.name} is null) errors["{c.name}"] = "obbligatorio";')
        if c.type == "string":
            w(f'        if (e.{c.name} is not null && e.{c.name}.Length > {c.length}) errors["{c.name}"] = "lunghezza massima {c.length}";')
    for r in t.relations:
        fc = t.col(r.foreign_key)
        if r.kind == "many_to_one" and fc.required:
            empty = "Guid.Empty" if fc.type == "uuid" else ("0L" if fc.type == "bigint" else "0")
            w(f'        if (e.{fc.name} == {empty} && e.{r.name} is null) errors["{fc.name}"] = "obbligatorio";')
    w(f'        if (errors.Count > 0) throw new ModelValidationException("{t.name}", errors);')
    w("    }")
    w("}\n")

    # ---- repository
    gen_cols = [c for c in t.columns if c.generated]
    w(f"/// <summary>CRUD e relazioni di {t.name}. I metodi custom vanno in model/{t.name}.cs (stessa partial class).</summary>")
    w(f"public partial class {repo}")
    w("{")
    w("    protected readonly AppDbContext Db;\n")
    w(f"    public {repo}(AppDbContext db)")
    w("    {")
    w("        Db = db;")
    if t.tenancy != "none":
        w(f"        Db.RequireTenant(); // tenancy: {t.tenancy}: senza un tenant legato al contesto il repository non lavora")
    w("    }\n")
    w(f"    protected DbSet<{t.name}> Set => Db.Set<{t.name}>();\n")
    tc = tenant_column(t)
    T = t.name
    S = "Scoped()" if tc else "Set"           # con tenancy: column ogni lettura parte dal filtro sul tenant
    if tc:
        w("    /// <summary>I record del tenant legato al contesto.</summary>")
        w(f"    protected IQueryable<{T}> Scoped()")
        w("    {")
        w("        var tenant = Db.RequireTenant();")
        w(f"        return Set.Where(x => x.{tc.name} == tenant);")
        w("    }\n")
        parents = [r for r in t.relations if r.kind == "many_to_one" and tables[r.target].tenancy == "column"]
        w("    /// <summary>Il record appartiene al tenant del contesto; i record collegati anche.</summary>")
        w(f"    protected async Task CheckTenantAsync({T} entity, CancellationToken ct)")
        w("    {")
        w("        var tenant = Db.RequireTenant();")
        empty_t = "Guid.Empty" if tc.type == "uuid" else "null"
        w(f"        if (entity.{tc.name} != {empty_t} && entity.{tc.name} != tenant)")
        w(f'            throw new ModelValidationException("{T}", new Dictionary<string, string> {{ ["{tc.name}"] = "tenant diverso da quello della sessione" }});')
        w(f"        entity.{tc.name} = tenant;")
        if parents:
            w("        var errors = new Dictionary<string, string>();")
            for r in parents:
                tg = tables[r.target]
                fkc = t.col(r.foreign_key)
                ttc = tenant_column(tg)
                tpk = tg.pk.name
                key_t = CS_TYPE[fkc.type] + ("?" if fkc.nullable else "")
                w(f"        {key_t} key{r.name} = entity.{r.name} is not null ? entity.{r.name}.{tpk} : entity.{r.foreign_key};")
                cond = f"key{r.name} is not null" if fkc.nullable else "true"
                w(f"        if ({cond} && !await Db.Set<{r.target}>().AnyAsync(p => p.{tpk} == key{r.name} && p.{ttc.name} == tenant, ct))")
                w(f'            errors["{r.foreign_key}"] = "non trovato";')
            w(f'        if (errors.Count > 0) throw new ModelValidationException("{T}", errors);')
        w("    }\n")

    def oi(cn, d):
        return f'new OrderItem("{cn}", "{member("typescript", cn)}", SortType.{_SORT[t.col(cn).type]}, {str(d).lower()})'
    w("    /// <summary>Contratto di paginazione della tabella: colonne ordinabili, ordine predefinito, limiti.</summary>")
    w("    public static readonly PagingSpec PageSpec = new(")
    w(f'        "{t.name}",')
    w(f"        {oi(pk.name, False)},")
    sortable = ", ".join(f'["{member("typescript", cn)}"] = {oi(cn, False)}' for cn in t.pagination.sortable)
    w(f"        new Dictionary<string, OrderItem> {{ {sortable} }},")
    w(f"        new[] {{ {', '.join(oi(cn, d) for cn, d in t.order())} }},")
    w(f"        {t.pagination.default_limit},")
    w(f"        {t.pagination.max_limit});\n")
    for q in t.queries:
        if q.returns != "one" or True:
            w(f"    private static readonly OrderItem[] Order{q.name} = {{ {', '.join(oi(cn, d) for cn, d in t.order(q.order_by or None))} }};\n")
    for meth in methods_of(t):
        k, _, arg = meth.key.partition(":")
        name = method_name(L, meth.key)
        w(f"    /// <summary>{meth.summary}</summary>")
        if k == "get_by_id" and t.archive and t.archive.read_through:
            ten = "Db.RequireTenant()" if t.tenancy != "none" else "null"
            w(f"    public async Task<{t.name}?> {name}({pkt} id, CancellationToken ct = default) =>")
            w(f"        await {S}.FirstOrDefaultAsync(x => x.{pk.name} == id, ct) ?? await FromArchiveAsync(id, ct);\n")
            w("    /// <summary>Record archiviato (archive.read_through): non tracciato dal contesto, in sola lettura.</summary>")
            w(f"    private async Task<{t.name}?> FromArchiveAsync({pkt} id, CancellationToken ct)")
            w("    {")
            w(f'        if (await Archive.ReadAsync(Db, "{t.db_name}", {ten}, id, ct) is not {{ }} doc) return null;')
            w(f"        return new {t.name}")
            w("        {")
            for c in t.columns:
                if c.type == "json":
                    v = f'Archive.Json(doc, "{c.name}")' + ("" if c.nullable else "!")
                else:
                    v = f'Archive.Get<{_prop_type(c)}>(doc, "{c.name}")'
                w(f"            {c.name} = {v},")
            w("        };")
            w("    }")
        elif k == "get_by_id":
            w(f"    public Task<{t.name}?> {name}({pkt} id, CancellationToken ct = default) =>")
            w(f"        {S}.FirstOrDefaultAsync(x => x.{pk.name} == id, ct);")
        elif k == "list_page":
            w(f"    public Task<Page<{t.name}>> {name}(PageRequest? page = null, CancellationToken ct = default) =>")
            w(f"        Paging.RunPageAsync({S}.AsNoTracking(), PageSpec, page, null, ct);")
        elif k == "count":
            w(f"    public Task<int> {name}(CancellationToken ct = default) => {S}.CountAsync(ct);")
        elif k == "exists":
            w(f"    public Task<bool> {name}({pkt} id, CancellationToken ct = default) =>")
            w(f"        {S}.AnyAsync(x => x.{pk.name} == id, ct);")
        elif k == "create":
            w(f"    public async Task<{t.name}> {name}({t.name} entity, CancellationToken ct = default)")
            w("    {")
            w(f"        {t.name}Validation.Validate(entity);")
            if tc:
                w("        await CheckTenantAsync(entity, ct);")
            for r in t.relations:
                if r.kind == "many_to_one":
                    w(f"        if (entity.{r.name} is not null && Db.Entry(entity.{r.name}).State == EntityState.Detached) Db.Attach(entity.{r.name});")
            w("        Set.Add(entity);")
            w("        await Db.SaveChangesAsync(ct);")
            w("        return entity;")
            w("    }")
        elif k == "update":
            w(f"    public async Task<{t.name}> {name}({t.name} entity, CancellationToken ct = default)")
            w("    {")
            empty = "Guid.Empty" if pk.type == "uuid" else ("null" if pk.type == "string" else "0")
            w(f'        if (entity.{pk.name} == {empty}) throw new ArgumentException("{t.name}: update senza chiave", nameof(entity));')
            w(f"        {t.name}Validation.Validate(entity);")
            w(f"        var key = entity.{pk.name};")
            w(f'        if (!await {S}.AnyAsync(x => x.{pk.name} == key, ct)) throw new KeyNotFoundException("{t.name}: record inesistente");')
            if tc:
                w("        await CheckTenantAsync(entity, ct);")
            w("        Db.Entry(entity).State = EntityState.Modified; // solo il record, non il grafo collegato")
            w("        await Db.SaveChangesAsync(ct);")
            if any(c.generated == "on_create" for c in gen_cols):
                w("        await Db.Entry(entity).ReloadAsync(ct); // riallinea i campi non modificabili")
            w("        return entity;")
            w("    }")
        elif k == "delete":
            w(f"    public async Task<bool> {name}({pkt} id, CancellationToken ct = default)")
            w("    {")
            w(f"        var entity = await {S}.FirstOrDefaultAsync(x => x.{pk.name} == id, ct);")
            w("        if (entity is null) return false;")
            w("        Set.Remove(entity);")
            w("        await Db.SaveChangesAsync(ct);")
            w("        return true;")
            w("    }")
        elif k == "find_by":
            c = t.col(arg)
            w(f"    public Task<{t.name}?> {name}({CS_TYPE[c.type]} value, CancellationToken ct = default) =>")
            w(f"        {S}.FirstOrDefaultAsync(x => x.{c.name} == value, ct);")
        elif k == "list_by":
            c = t.col(arg)
            w(f"    public Task<Page<{t.name}>> {name}({CS_TYPE[c.type]} value, PageRequest? page = null, CancellationToken ct = default) =>")
            w(f"        Paging.RunPageAsync({S}.AsNoTracking().Where(x => x.{c.name} == value), PageSpec, page, null, ct);")
        elif k == "get_rel":
            r = next(x for x in t.relations if x.name == arg)
            w(f"    public async Task<{r.target}?> {name}({pkt} id, CancellationToken ct = default)")
            w("    {")
            w(f"        var entity = await {S}.Include(x => x.{r.name}).FirstOrDefaultAsync(x => x.{pk.name} == id, ct);")
            w(f"        return entity?.{r.name};")
            w("    }")
        elif k == "list_rel":
            r = next(x for x in t.relations if x.name == arg)
            ctc = tenant_column(tables[r.target])
            if ctc:
                w(f"    public Task<Page<{r.target}>> {name}({pkt} id, PageRequest? page = null, CancellationToken ct = default)")
                w("    {")
                w("        var tenant = Db.RequireTenant();")
                w(f"        return Paging.RunPageAsync(Db.Set<{r.target}>().AsNoTracking().Where(x => x.{r.foreign_key} == id && x.{ctc.name} == tenant), "
                  f"{repo_class(L, r.target)}.PageSpec, page, null, ct);")
                w("    }")
            else:
                w(f"    public Task<Page<{r.target}>> {name}({pkt} id, PageRequest? page = null, CancellationToken ct = default) =>")
                w(f"        Paging.RunPageAsync(Db.Set<{r.target}>().AsNoTracking().Where(x => x.{r.foreign_key} == id), {repo_class(L, r.target)}.PageSpec, page, null, ct);")
        elif k in ("query_page", "query_list", "query_one"):
            q = next(x for x in t.queries if x.name == arg)
            params, conds, guards = [], [], []
            for c in q.where:
                col = t.col(c.column)
                ct_ = CS_TYPE[col.type]
                if c.param:
                    pn = c.param[:1].lower() + c.param[1:]
                    params.append(f"IReadOnlyCollection<{ct_}> {pn}" if c.op == "in" else f"{ct_} {pn}")
                    val = pn
                    if c.op == "in":
                        guards.append(pn)
                else:
                    val = _cs_value(col, c.value) if c.has_value else None
                conds.append(_cs_cond(f"x.{c.column}", col.type, c.op, val))
            where = " && ".join(conds)
            ret = {"query_page": f"Page<{t.name}>", "query_list": f"List<{t.name}>", "query_one": f"{t.name}?"}[k]
            extra = ["PageRequest? page = null"] if k == "query_page" else []
            w(f"    public async Task<{ret}> {name}({', '.join(params + extra + ['CancellationToken ct = default'])})")
            w("    {")
            for g in guards:
                empty = {"query_page": f"Paging.EmptyPage<{t.name}>(PageSpec, page)", "query_list": f"new List<{t.name}>()", "query_one": "null"}[k]
                w(f"        if ({g}.Count == 0) return {empty};")
            for c in q.where:
                if c.param and c.op == "in":
                    pn = c.param[:1].lower() + c.param[1:]
                    ct_ = CS_TYPE[t.col(c.column).type]
                    w(f"        var {pn}Array = {pn} as {ct_}[] ?? {pn}.ToArray(); // array: tradotto come = ANY(@p)")
            w(f"        var query = {S}.AsNoTracking().Where(x => {where});")
            if k == "query_page":
                w(f"        return await Paging.RunPageAsync(query, PageSpec, page, Order{q.name}, ct);")
            elif k == "query_list":
                w(f"        return await Paging.OrderRows(query, Order{q.name}).Take(PageSpec.MaxLimit).ToListAsync(ct);")
            else:
                w(f"        return await Paging.OrderRows(query, Order{q.name}).FirstOrDefaultAsync(ct);")
            w("    }")
        w("")
    out[-1] = out[-1].rstrip("\n")
    w("}")
    return "\n".join(out) + "\n"


def _context_file(tables: Dict[str, Table], ns: str) -> str:
    out = [header(L, "kit") + "// <auto-generated />", "#nullable enable", "using System;", "using System.Threading;",
           "using System.Threading.Tasks;", "using Microsoft.EntityFrameworkCore;\n",
           f"namespace {ns};\n",
           "/// <summary>DbContext con tutte le tabelle e le relazioni dichiarate negli schemi.</summary>",
           "public partial class AppDbContext : DbContext", "{",
           "    public AppDbContext(DbContextOptions<AppDbContext> options) : base(options)", "    {", "    }\n"]
    for n in tables:
        out.append(f"    public DbSet<{n}> {n} => Set<{n}>();")
    out.append("\n    protected override void OnModelCreating(ModelBuilder modelBuilder)")
    out.append("    {")
    for n, t in tables.items():
        for r in t.relations:
            if r.kind != "many_to_one":
                continue
            od = {"restrict": "Restrict", "cascade": "Cascade", "set_null": "SetNull"}[r.on_delete]
            inv = f"x => x.{r.inverse}" if r.inverse else ""
            req = "true" if t.col(r.foreign_key).required else "false"
            out.append(f"        modelBuilder.Entity<{n}>().HasOne(x => x.{r.name}).WithMany({inv})"
                       f".HasForeignKey(x => x.{r.foreign_key}).IsRequired({req}).OnDelete(DeleteBehavior.{od});")
    out.append("        OnModelCreatingCustom(modelBuilder);")
    out.append("    }\n")
    stamped = [(n, t) for n, t in tables.items() if any(c.generated for c in t.columns)]
    if stamped:
        out += ["    public override int SaveChanges(bool acceptAllChangesOnSuccess)", "    {",
                "        ApplyGeneratedTimestamps();", "        return base.SaveChanges(acceptAllChangesOnSuccess);", "    }\n",
                "    public override Task<int> SaveChangesAsync(bool acceptAllChangesOnSuccess, CancellationToken cancellationToken = default)",
                "    {", "        ApplyGeneratedTimestamps();",
                "        return base.SaveChangesAsync(acceptAllChangesOnSuccess, cancellationToken);", "    }\n",
                "    /// <summary>Date generate (on_create / on_update) su ogni record inserito o modificato, anche nei grafi collegati.</summary>",
                "    private void ApplyGeneratedTimestamps()", "    {", "        var now = DateTimeOffset.UtcNow;"]
        for n, t in stamped:
            oc = [c.name for c in t.columns if c.generated == "on_create"]
            ou = [c.name for c in t.columns if c.generated == "on_update"]
            out.append(f"        foreach (var entry in ChangeTracker.Entries<{n}>())")
            out.append("        {")
            out.append("            if (entry.State == EntityState.Added)")
            out.append("            {")
            for c in oc + ou:
                out.append(f"                entry.Entity.{c} = now;")
            out.append("            }")
            out.append("            else if (entry.State == EntityState.Modified)")
            out.append("            {")
            for c in oc:
                out.append(f"                entry.Property(x => x.{c}).IsModified = false;")
            for c in ou:
                out.append(f"                entry.Entity.{c} = now;")
            out.append("            }")
            out.append("        }")
        out += ["    }\n"]
    out.append("    /// <summary>Configurazioni aggiuntive: implementala in un file partial fuori da generated/.</summary>")
    out.append("    partial void OnModelCreatingCustom(ModelBuilder modelBuilder);")
    out.append("}")
    return "\n".join(out) + "\n"


def _common_file(ns: str) -> str:
    return (header(L, "kit") + "// <auto-generated />\n#nullable enable\nusing System;\nusing System.Collections.Generic;\nusing System.Linq;\n\n"
            f"namespace {ns};\n\n"
            "/// <summary>Dati non validi per la tabella: Fields contiene campo -> regola violata (mai valori).</summary>\n"
            "public sealed class ModelValidationException : Exception\n{\n"
            "    public ModelValidationException(string table, IReadOnlyDictionary<string, string> fields)\n"
            '        : base($"{table}: dati non validi ({string.Join(", ", fields.Keys.OrderBy(k => k))})")\n'
            "    {\n        Table = table;\n        Fields = fields;\n    }\n\n"
            "    public string Table { get; }\n\n"
            "    public IReadOnlyDictionary<string, string> Fields { get; }\n}\n")


def custom_stub(t: Table, ns: str) -> str:
    return (f"// {t.name}: punto d'ingresso per l'accesso ai dati della tabella {t.db_name}.\n"
            f"// CRUD e relazioni sono in generated/{t.name}.cs, nella stessa partial class (vedi MODEL_INDEX.md).\n"
            "// Qui vanno SOLO i metodi custom di questa tabella, con nomi diversi da quelli generati.\n"
            "#nullable enable\n"
            "using System.Linq;\n"
            "using System.Threading;\n"
            "using System.Threading.Tasks;\n"
            + ("using MongoDB.Driver;\n\n" if t.mongo else "using Microsoft.EntityFrameworkCore;\n\n") +
            f"namespace {ns};\n\n"
            f"public partial class {repo_class(L, t.name)}\n"
            "{\n"
            "}\n")


def emit(tables: Dict[str, Table], schema_rel: Dict[str, str], opts: Dict) -> Tuple[Dict[str, str], Dict[str, str]]:
    ns, dialect = opts["namespace"], opts.get("dialect", "postgres")
    gen = {f"{GEN_DIR}/AppDbContext.cs": _context_file({n: t for n, t in tables.items() if not t.mongo}, ns), f"{GEN_DIR}/ModelValidationException.cs": _common_file(ns),
           f"{GEN_DIR}/Paging.cs": runtime_csharp.paging_file(ns), f"{GEN_DIR}/UnitOfWork.cs": runtime_csharp.uow_file(ns, tables),
           f"{GEN_DIR}/Tenancy.cs": runtime_tenant.csharp_file(ns, opts.get("tenant_id_type", "uuid")),
           f"{GEN_DIR}/Archive.cs": runtime_archive.csharp_file(ns)}
    for n, t in tables.items():
        gen[f"{GEN_DIR}/{n}.cs"] = (_mongo_table_file(t, tables, schema_rel[n], ns) if t.mongo
                                    else _table_file(t, tables, schema_rel[n], ns, dialect))
    if any(t.mongo for t in tables.values()):
        gen[f"{GEN_DIR}/MongoSession.cs"] = runtime_mongo.csharp_file(ns, opts.get("tenant_id_type", "uuid"))
        gen[f"{GEN_DIR}/MongoIndexes.cs"] = _mongo_indexes_file(tables, ns)
    custom = {custom_file(L, n): custom_stub(t, ns) for n, t in tables.items()}
    return gen, custom


_SORT = {"uuid": "Uuid", "string": "String", "int": "Int", "bigint": "BigInt", "decimal": "Decimal", "date": "Date", "datetime": "DateTime"}


def _cs_value(col, v) -> str:
    if isinstance(v, list):
        return "new[] { " + ", ".join(_cs_value(col, x) for x in v) + " }"
    if col.type == "uuid":
        return f'Guid.Parse("{v}")'
    if col.type == "decimal":
        return f"{v}m"
    if col.type == "bigint":
        return f"{int(v)}L"
    if col.type == "int":
        return str(int(v))
    if col.type == "bool":
        return "true" if v else "false"
    if col.type == "date":
        return f'DateOnly.Parse("{v}", System.Globalization.CultureInfo.InvariantCulture)'
    if col.type == "datetime":
        return f'DateTimeOffset.Parse("{v}", System.Globalization.CultureInfo.InvariantCulture)'
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def _cs_cond(prop: str, typ: str, op: str, val) -> str:
    if op == "is_null":
        return f"{prop} == null"
    if op == "not_null":
        return f"{prop} != null"
    if op == "in":
        return f"{val}Array.Contains({prop})"
    if op == "prefix":
        return f'EF.Functions.Like({prop}, Paging.LikePrefix({val}), "\\\\")'
    sym = {"eq": "==", "ne": "!=", "lt": "<", "lte": "<=", "gt": ">", "gte": ">="}[op]
    if op in ("lt", "lte", "gt", "gte") and typ in ("string", "uuid"):
        return f"{prop}.CompareTo({val}) {sym} 0"
    return f"{prop} {sym} {val}"


