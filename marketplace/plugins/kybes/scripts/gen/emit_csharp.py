def _empty_key(c) -> str:
    return "Guid.Empty" if c.type == "uuid" else ("null" if c.type in REF_TYPES else ("0L" if c.type == "bigint" else "0"))


def _mongo_cond(field: str, op: str, val: str, typ: str) -> str:
    v = f'MongoSession.ToBson({val}, "{typ}")'
    if op == "eq":
        return f'new BsonDocument("{field}", {v})'
    if op == "ne":
        return f'new BsonDocument("{field}", new BsonDocument("$nin", new BsonArray {{ {v}, BsonNull.Value }}))'
    if op in ("lt", "lte", "gt", "gte"):
        return f'new BsonDocument("{field}", new BsonDocument("${op}", {v}))'
    if op == "in":
        return f'new BsonDocument("{field}", new BsonDocument("$in", new BsonArray({val}.Select(x => MongoSession.ToBson(x, "{typ}")))))'
    if op == "prefix":
        return f'new BsonDocument("{field}", MongoSession.Prefix({val}))'
    if op == "is_null":
        return f'new BsonDocument("{field}", BsonNull.Value)'
    return f'new BsonDocument("{field}", new BsonDocument("$ne", BsonNull.Value))'


