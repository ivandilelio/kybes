"""Prodotti indipendenti dal linguaggio: DDL PostgreSQL, report degli indici, contratto di pagina."""
from __future__ import annotations

import json
from typing import Dict, List

from naming import MARKER
from schema import Table, index_plan, snake

PG_TYPE = {"uuid": "uuid", "text": "text", "int": "integer", "bigint": "bigint", "bool": "boolean",
           "date": "date", "datetime": "timestamptz", "json": "jsonb"}


def _q(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def _pg_type(c) -> str:
    if c.type == "string":
        return f"varchar({c.length})"
    if c.type == "decimal":
        return f"numeric({c.precision}, {c.scale})"
    return PG_TYPE[c.type]


def _pg_default(c) -> str:
    v = c.default
    if isinstance(v, bool):
        return "true" if v else "false"
    if c.type in ("int", "bigint", "decimal"):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def ddl_table(t: Table) -> List[str]:
    cols = []
    for c in t.columns:
        parts = [_q(c.db_name), _pg_type(c)]
        if c.primary_key and c.auto:
            parts.append("DEFAULT gen_random_uuid()" if c.type == "uuid" else "GENERATED BY DEFAULT AS IDENTITY")
        if not c.nullable:
            parts.append("NOT NULL")
        if c.default is not None:
            parts.append("DEFAULT " + _pg_default(c))
        if c.generated == "on_create":
            parts.append("DEFAULT now()")
        cols.append("    " + " ".join(parts))
    cols.append(f"    CONSTRAINT {_q('pk_' + t.db_name)} PRIMARY KEY ({_q(t.pk.db_name)})")
    plan = index_plan(t)
    for s in plan.specs:
        if s.unique:
            cols.append(f"    CONSTRAINT {_q(s.name)} UNIQUE ({', '.join(_q(t.col(c).db_name) for c in s.columns)})")
    out = [f"CREATE TABLE {_q(t.db_name)} (", ",\n".join(cols), ");"]
    if t.description:
        out.append(f"COMMENT ON TABLE {_q(t.db_name)} IS '{t.description.replace(chr(39), chr(39) * 2)}';")
    return out


def ddl_foreign_keys(t: Table, tables: Dict[str, Table]) -> List[str]:
    out = []
    for r in t.relations:
        if r.kind != "many_to_one":
            continue
        tg = tables[r.target]
        od = {"restrict": "RESTRICT", "cascade": "CASCADE", "set_null": "SET NULL"}[r.on_delete]
        out.append(f"ALTER TABLE {_q(t.db_name)} ADD CONSTRAINT {_q('fk_' + t.db_name + '_' + t.col(r.foreign_key).db_name)} "
                   f"FOREIGN KEY ({_q(t.col(r.foreign_key).db_name)}) REFERENCES {_q(tg.db_name)} ({_q(tg.pk.db_name)}) ON DELETE {od};")
    return out


def _ix_col(t: Table, s, c: str) -> str:
    if c in s.pattern:
        ops = "text_pattern_ops" if t.col(c).type == "text" else "varchar_pattern_ops"
        return f"{_q(t.col(c).db_name)} {ops}"
    return _q(t.col(c).db_name)


def ddl_indexes(t: Table) -> List[str]:
    return [f"CREATE INDEX {_q(s.name)} ON {_q(t.db_name)} ({', '.join(_ix_col(t, s, c) for c in s.columns)});"
            for s in index_plan(t).specs if not s.unique]


def _head(src: str) -> str:
    return f"-- {MARKER}. NON MODIFICARE: rigenerato da {src}.\n"


def ddl_files(tables: Dict[str, Table], schema_dir: str) -> Dict[str, str]:
    files = {}
    for n, t in tables.items():
        body = ddl_table(t) + [""] + ddl_foreign_keys(t, tables) + [""] + ddl_indexes(t)
        files[f"{n}.sql"] = _head(f"{schema_dir}/{n}.yaml") + "-- Per creare lo schema completo usa _all.sql (ordine corretto delle tabelle).\n\n" + \
            "\n".join(body).strip() + "\n"
    allp = [_head(schema_dir) + "-- Schema completo PostgreSQL 13+: tabelle, poi chiavi esterne, poi indici.\n"]
    for t in tables.values():
        allp += ddl_table(t) + [""]
    for t in tables.values():
        allp += ddl_foreign_keys(t, tables)
    allp.append("")
    for t in tables.values():
        allp += ddl_indexes(t)
    files["_all.sql"] = "\n".join(allp).strip() + "\n"
    return files


def index_report(tables: Dict[str, Table]) -> str:
    o = [f"<!-- {MARKER}. NON MODIFICARE: rigenerato dagli schemi. -->", "# Analisi degli indici", "",
         "Per ogni percorso di accesso (ricerche univoche, chiavi esterne, ordinamenti ammessi, query dichiarate) "
         "il generatore calcola l'indice ideale: prima le colonne di uguaglianza, poi quelle di ordinamento o di intervallo. "
         "Se un indice esistente lo copre viene riusato, altrimenti viene creato. I nomi sono identici in tutti i linguaggi e nel DDL.", ""]
    total_new = 0
    warnings = []
    for n, t in tables.items():
        plan = index_plan(t, tables)
        o += [f"## {n}", "", "| Accesso | Colonne ideali | Indice | Esito |", "|---|---|---|---|"]
        for p in plan.paths:
            if not p.ideal:
                esito, ix = "nessun indice necessario", "—"
            elif p.covered_by:
                esito, ix = "coperto", f"`{p.covered_by}`"
            elif p.created:
                esito, ix = "creato", f"`{p.created}`"
                total_new += 1
            else:
                esito, ix = "chiave primaria", "PK"
            o.append(f"| {p.label} | {', '.join(p.ideal) or '—'} | {ix} | {esito} |")
        o += ["", "| Indice | Colonne | Univoco | Origine |", "|---|---|---|---|"]
        for s in plan.specs:
            origin = s.origin + (" (solo DDL PostgreSQL, operator class per LIKE)" if s.ddl_only else "")
            o.append(f"| `{s.name}` | {', '.join(s.columns)} | {'sì' if s.unique else 'no'} | {origin} |")
        for r in plan.redundant:
            warnings.append(f"- {n}: {r}")
        o.append("")
    o += ["## Avvisi", ""] + (warnings or ["Nessun indice ridondante."])
    o.insert(5, f"Indici creati automaticamente per coprire gli accessi: **{total_new}**.\n")
    return "\n".join(o) + "\n"


def page_schema() -> str:
    doc = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "_page.schema.json",
        "$comment": f"{MARKER}. Contratto di paginazione a cursore comune a tutte le tabelle.",
        "title": "Paginazione a cursore",
        "$defs": {
            "PageRequest": {
                "type": "object", "additionalProperties": False,
                "description": "Parametri di query della richiesta: ?limit=50&cursor=...&sort=-data,numero",
                "properties": {
                    "limit": {"type": "integer", "minimum": 1, "description": "righe per pagina, al massimo max_limit della tabella"},
                    "cursor": {"type": "string", "description": "next_cursor della pagina precedente, opaco"},
                    "sort": {"type": "string", "pattern": "^[-+]?[a-z][A-Za-z0-9]*(,[-+]?[a-z][A-Za-z0-9]*)*$",
                             "description": "colonne ordinabili (nomi JSON), '-' per discendente"},
                },
            },
            "Page": {
                "type": "object", "additionalProperties": False, "required": ["items", "nextCursor", "limit"],
                "properties": {
                    "items": {"type": "array"},
                    "nextCursor": {"type": ["string", "null"], "description": "null se non ci sono altre pagine"},
                    "limit": {"type": "integer"},
                },
            },
        },
    }
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
