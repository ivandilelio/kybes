def builders_file(ns: str, tables: Dict[str, Table]) -> str:
    o = [header(L, "kit") + "// <auto-generated />", "#nullable enable", *USINGS, "using System.Threading;", f"using {ns};", "",
         f"namespace {_ns(ns)};", "",
         "/// <summary>Costruttori di dati validi per i test generati e custom: un record per chiamata, valori deterministici.</summary>",
         "public static class KybesBuilders", "{",
         "    /// <summary>Tenant di prova: KybesDb.Open() lega TENANT_A.</summary>",
         f"    public static readonly {_TC[0]} TENANT_A = {_tval('a')};", f"    public static readonly {_TC[0]} TENANT_B = {_tval('b')};", "",
         "    private static int seq;", "",
         "    public static int NextN() => Interlocked.Increment(ref seq);", "",
         "    public static string TextValue(int n, int length)", "    {", '        var s = "v" + n;',
         "        return s.Length > length ? s[..length] : s;", "    }", "",
         "    /// <summary>Confronto tra valori di una colonna: -1, 0, 1 (date-ora per istante, UUID e testi come in PostgreSQL).</summary>",
         "    public static int Cmp(object? a, object? b)", "    {",
         "        if (a is null || b is null) return a is null && b is null ? 0 : (a is null ? -1 : 1);",
         "        if (a is DateTimeOffset x && b is DateTimeOffset y) return Math.Sign(x.UtcDateTime.CompareTo(y.UtcDateTime));",
         "        if (a is Guid g && b is Guid h) return Math.Sign(string.CompareOrdinal(g.ToString(), h.ToString()));",
         "        if (a is string s && b is string t) return Math.Sign(string.CompareOrdinal(s, t));",
         "        if (a is int or long or decimal && b is int or long or decimal) return Math.Sign(Convert.ToDecimal(a).CompareTo(Convert.ToDecimal(b)));",
         "        return Math.Sign(((IComparable)a).CompareTo(b));", "    }", "",
         "    /// <summary>Un valore dello stesso tipo, sicuramente diverso (testi entro length caratteri).</summary>",
         "    public static T Different<T>(T v, int length = 0)", "    {", "        object o = v switch", "        {",
         "            Guid => Guid.NewGuid(),", "            int i => i + 1000003,", "            long l => l + 1000003L,",
         "            decimal d => d + 1000003m,", "            bool b => !b,", "            DateOnly d => d.AddDays(401),",
         "            DateTimeOffset d => d.AddDays(401),", "            _ => Text(v?.ToString() ?? \"\", length),", "        };",
         "        return (T)o;", "    }", "",
         "    private static string Text(string s, int length)", "    {", '        var o = "x" + s;',
         "        if (length > 0 && o.Length > length) o = o[..length];", '        return o == s ? o[..^1] + "y" : o;', "    }", "",
         "    public static T Greater<T>(T v)", "    {", "        object o = v switch", "        {",
         '            Guid => Guid.Parse("ffffffff-ffff-ffff-ffff-ffffffffffff"),', "            int i => i + 1,", "            long l => l + 1L,",
         "            decimal d => d + 1m,", "            DateOnly d => d.AddDays(1),", "            DateTimeOffset d => d.AddDays(1),",
         '            _ => v + "~",', "        };", "        return (T)o;", "    }", "",
         "    public static T Smaller<T>(T v)", "    {", "        object o = v switch", "        {",
         "            Guid => Guid.Empty,", "            int i => i - 1,", "            long l => l - 1L,", "            decimal d => d - 1m,",
         "            DateOnly d => d.AddDays(-1),", "            DateTimeOffset d => d.AddDays(-1),", '            _ => "",', "        };",
         "        return (T)o;", "    }"]
    for n, t in tables.items():
        o += ["", f"    /// <summary>Inserisce un {n} valido; over cambia i valori prima dell'inserimento.</summary>",
              f"    public static async Task<{n}> Build{n}({'MongoSession' if t.mongo else 'AppDbContext'} db, Action<{n}>? over = null)", "    {", f"        var e = new {n}();"]
        for c in t.columns:
            if (c.primary_key and c.auto) or c.generated or c.default is not None or c.tenant:
                continue
            rel = next((r for r in t.relations if r.kind == "many_to_one" and r.foreign_key == c.name), None)
            if rel and not c.required:
                continue
            o.append(f"        e.{c.name} = {_sample(t, c.name, tables)};")
        o += ["        over?.Invoke(e);", f"        return await new {repo_class(L, n)}(db).CreateAsync(e);", "    }"]
    o.append("}")
    return "\n".join(o) + "\n"


