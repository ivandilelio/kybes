def _for_mongo(o: List[str]) -> List[str]:
    """Test di una collection MongoDB: MongoSession al posto dell'AppDbContext; le riletture usano una sessione nuova."""
    out = []
    for x in o:
        if x.strip() == "db.ChangeTracker.Clear();":
            continue
        if x == "using Microsoft.EntityFrameworkCore;":
            out += ["using MongoDB.Bson;", "using MongoDB.Driver;"]
            continue
        x = (x.replace("private readonly AppDbContext db = KybesDb.Open();", "private readonly MongoSession db = KybesMongo.Open();")
             .replace("public void Dispose() => db.Dispose();", "public void Dispose() => KybesMongo.Close(db);")
             .replace("using var check = KybesDb.NewContext();", "var check = KybesMongo.Again(db);"))
        out.append(x)
    return out


