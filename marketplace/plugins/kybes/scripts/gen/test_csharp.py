def db_file(ns: str, tables: Dict[str, Table]) -> str:
    names = ", ".join('\\"' + t.db_name + '\\"' for t in tables.values())
    return header(L, "kit") + f'''// <auto-generated />
#nullable enable
using System;
using System.Collections.Generic;
using System.Threading.Tasks;
using Microsoft.EntityFrameworkCore;
using {ns};
using Xunit;

// i test condividono un database: niente esecuzione in parallelo
[assembly: CollectionBehavior(DisableTestParallelization = true)]

namespace {_ns(ns)};

/// <summary>
/// Database dei test generati e custom: il PostgreSQL indicato da KYBES_TEST_DATABASE_URL
/// (postgresql://utente:password@host:porta/database oppure una connection string Npgsql).
/// Lo schema lo crea EF Core dal modello; ogni test parte da tabelle vuote.
/// </summary>
public static class KybesDb
{{
    private static readonly object Gate = new();
    private static bool created;

    public static string ConnectionString()
    {{
        var url = Environment.GetEnvironmentVariable("KYBES_TEST_DATABASE_URL");
        if (string.IsNullOrWhiteSpace(url))
            throw new InvalidOperationException("Imposta KYBES_TEST_DATABASE_URL (PostgreSQL di test) per eseguire i test generati");
        if (!url.Contains("://")) return url;
        var u = new Uri("http://" + url[(url.IndexOf("://", StringComparison.Ordinal) + 3)..]);
        var info = u.UserInfo.Split(':', 2);
        var cs = $"Host={{u.Host}};Port={{(u.Port > 0 ? u.Port : 5432)}};Database={{u.AbsolutePath.TrimStart('/')}}";
        if (info[0].Length > 0) cs += $";Username={{Uri.UnescapeDataString(info[0])}}";
        if (info.Length > 1) cs += $";Password={{Uri.UnescapeDataString(info[1])}}";
        return cs;
    }}

    /// <summary>Un contesto nuovo sullo stesso database, senza svuotarlo: per rileggere i dati.</summary>
    public static AppDbContext NewContext() =>
        new(new DbContextOptionsBuilder<AppDbContext>().UseNpgsql(ConnectionString()).Options);

    /// <summary>Tabelle vuote e un contesto nuovo.</summary>
    public static AppDbContext Open()
    {{
        lock (Gate)
        {{
            if (!created)
            {{
                using var init = NewContext();
                init.Database.EnsureDeleted();
                init.Database.EnsureCreated();
                created = true;
            }}
        }}
        var db = NewContext();
        db.Database.ExecuteSqlRaw("TRUNCATE TABLE {names} RESTART IDENTITY CASCADE");
        return db;
    }}

    /// <summary>L'operazione è rifiutata con un errore di validazione sul campo indicato.</summary>
    public static async Task<ModelValidationException> AssertInvalid(string field, Func<Task> operation)
    {{
        var e = await Assert.ThrowsAsync<ModelValidationException>(operation);
        Assert.True(e.Fields.ContainsKey(field), $"errore atteso su {{field}}, trovati {{string.Join(", ", e.Fields.Keys)}}");
        return e;
    }}

    public static ModelValidationException AssertInvalidNow(string field, Action operation)
    {{
        var e = Assert.Throws<ModelValidationException>(operation);
        Assert.True(e.Fields.ContainsKey(field), $"errore atteso su {{field}}, trovati {{string.Join(", ", e.Fields.Keys)}}");
        return e;
    }}

    public static async Task AssertRule(string field, string rule, Func<Task> operation) =>
        Assert.Equal(rule, (await AssertInvalid(field, operation)).Fields[field]);
}}
'''


def builders_file(ns: str, tables: Dict[str, Table]) -> str:
    o = [header(L, "kit") + "// <auto-generated />", "#nullable enable", *USINGS, "using System.Threading;", f"using {ns};", "",
         f"namespace {_ns(ns)};", "",
         "/// <summary>Costruttori di dati validi per i test generati e custom: un record per chiamata, valori deterministici.</summary>",
         "public static class KybesBuilders", "{", "    private static int seq;", "",
         "    public static int NextN() => Interlocked.Increment(ref seq);", "",
         "    public static string TextValue(int n, int length)", "    {", '        var s = "v" + n;',
         "        return s.Length > length ? s[..length] : s;", "    }", "",
         "    /// <summary>Confronto tra valori di una colonna: -1, 0, 1 (date-ora per istante, UUID e testi come in PostgreSQL).</summary>",
         "    public static int Cmp(object? a, object? b)", "    {",
         "        if (a is null || b is null) return a is null && b is null ? 0 : (a is null ? -1 : 1);",
         "        if (a is DateTimeOffset x && b is DateTimeOffset y) return Math.Sign(x.UtcDateTime.CompareTo(y.UtcDateTime));",
         "        if (a is Guid g && b is Guid h) return Math.Sign(string.CompareOrdinal(g.ToString(), h.ToString()));",
         "        if (a is string s && b is string t) return Math.Sign(string.CompareOrdinal(s, t));",
         "        if (a is int or long or decimal && b is int or long or decimal) return Math.Sign(Convert.ToDecimal(a).CompareTo(Convert.ToDecimal(b)));",
         "        return Math.Sign(((IComparable)a).CompareTo(b));", "    }", "",
         "    /// <summary>Un valore dello stesso tipo, sicuramente diverso (testi entro length caratteri).</summary>",
         "    public static T Different<T>(T v, int length = 0)", "    {", "        object o = v switch", "        {",
         "            Guid => Guid.NewGuid(),", "            int i => i + 1000003,", "            long l => l + 1000003L,",
         "            decimal d => d + 1000003m,", "            bool b => !b,", "            DateOnly d => d.AddDays(401),",
         "            DateTimeOffset d => d.AddDays(401),", "            _ => Text(v?.ToString() ?? \"\", length),", "        };",
         "        return (T)o;", "    }", "",
         "    private static string Text(string s, int length)", "    {", '        var o = "x" + s;',
         "        if (length > 0 && o.Length > length) o = o[..length];", '        return o == s ? o[..^1] + "y" : o;', "    }", "",
         "    public static T Greater<T>(T v)", "    {", "        object o = v switch", "        {",
         '            Guid => Guid.Parse("ffffffff-ffff-ffff-ffff-ffffffffffff"),', "            int i => i + 1,", "            long l => l + 1L,",
         "            decimal d => d + 1m,", "            DateOnly d => d.AddDays(1),", "            DateTimeOffset d => d.AddDays(1),",
         '            _ => v + "~",', "        };", "        return (T)o;", "    }", "",
         "    public static T Smaller<T>(T v)", "    {", "        object o = v switch", "        {",
         "            Guid => Guid.Empty,", "            int i => i - 1,", "            long l => l - 1L,", "            decimal d => d - 1m,",
         "            DateOnly d => d.AddDays(-1),", "            DateTimeOffset d => d.AddDays(-1),", '            _ => "",', "        };",
         "        return (T)o;", "    }"]
    for n, t in tables.items():
        o += ["", f"    /// <summary>Inserisce un {n} valido; over cambia i valori prima dell'inserimento.</summary>",
              f"    public static async Task<{n}> Build{n}(AppDbContext db, Action<{n}>? over = null)", "    {", f"        var e = new {n}();"]
        for c in t.columns:
            if (c.primary_key and c.auto) or c.generated or c.default is not None:
                continue
            rel = next((r for r in t.relations if r.kind == "many_to_one" and r.foreign_key == c.name), None)
            if rel and not c.required:
                continue
            o.append(f"        e.{c.name} = {_sample(t, c.name, tables)};")
        o += ["        over?.Invoke(e);", f"        return await new {repo_class(L, n)}(db).CreateAsync(e);", "    }"]
    o.append("}")
    return "\n".join(o) + "\n"


