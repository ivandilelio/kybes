def mongo_file(ns: str) -> str:
    return header(L, "kit") + f'''// <auto-generated />
#nullable enable
using System;
using MongoDB.Driver;
using {ns};

namespace {_ns(ns)};

/// <summary>
/// Database MongoDB dei test delle collection (storage: mongo): il server indicato da KYBES_TEST_MONGO_URL (replica set,
/// per le transazioni). Ogni test lavora in un database nuovo con gli indici del modello, eliminato alla fine.
/// </summary>
public static class KybesMongo
{{
    private static readonly object Gate = new();
    private static MongoClient? client;

    public static IMongoClient Client()
    {{
        lock (Gate)
        {{
            if (client is null)
            {{
                var url = Environment.GetEnvironmentVariable("KYBES_TEST_MONGO_URL");
                if (string.IsNullOrWhiteSpace(url))
                    throw new InvalidOperationException("Imposta KYBES_TEST_MONGO_URL (MongoDB con replica set) per eseguire i test delle collection");
                client = new MongoClient(url);
            }}
            return client;
        }}
    }}

    /// <summary>Database vuoto con gli indici e TENANT_A legato.</summary>
    public static MongoSession Open()
    {{
        var db = Client().GetDatabase("kybes_test_" + Guid.NewGuid().ToString("N"));
        MongoIndexes.EnsureAsync(db).GetAwaiter().GetResult();
        return Again(new MongoSession(db));
    }}

    /// <summary>Una sessione nuova sullo stesso database, legata a TENANT_A: per rileggere i dati.</summary>
    public static MongoSession Again(MongoSession em)
    {{
        var fresh = new MongoSession(em.Db);
        fresh.BindTenant(KybesBuilders.TENANT_A);
        return fresh;
    }}

    public static void Close(MongoSession em) => em.Db.Client.DropDatabase(em.Db.DatabaseNamespace.DatabaseName);
}}
'''


