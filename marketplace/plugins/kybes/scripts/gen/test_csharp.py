def emit(cat: Catalog, tables: Dict[str, Table], default_asil: str, ns: str = "App.Model") -> Dict[str, str]:
    """File relativi alla cartella dei test C# del pacchetto (es. libs/db-models/csharp/tests)."""
    _TC[0] = "Guid" if cat.tenant_id_type == "uuid" else "string"
    files = {"generated/KybesDb.cs": db_file(ns, tables), "generated/KybesBuilders.cs": builders_file(ns, tables)}
    for n, t in tables.items():
        files[f"generated/{n}Tests.cs"] = test_file(ns, t, cat, tables, default_asil)
    files["generated/KybesRuntimeTests.cs"] = runtime_file(ns, cat, tables)
    if any(t.mongo for t in tables.values()):
        files["generated/KybesMongo.cs"] = mongo_file(ns)
    return files
