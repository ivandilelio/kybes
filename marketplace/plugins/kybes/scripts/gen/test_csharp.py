def _check(a: str, op: str, val) -> str:
    x = f"x.{a}"
    return {"eq": f"Cmp({x}, {val}) == 0", "ne": f"Cmp({x}, {val}) != 0", "lt": f"Cmp({x}, {val}) < 0",
            "lte": f"Cmp({x}, {val}) <= 0", "gt": f"Cmp({x}, {val}) > 0", "gte": f"Cmp({x}, {val}) >= 0",
            "in": f"{val}.Any(v => Cmp({x}, v) == 0)", "prefix": f'({x}?.ToString() ?? "").StartsWith({val}, StringComparison.Ordinal)',
            "is_null": f"{x} is null", "not_null": f"{x} is not null"}[op]


def _query_case(t: Table, tc: TestCase, tables: Dict[str, Table]) -> List[str]:
    q = next(x for x in t.queries if x.name == tc.args["query"])
    flip, empty = tc.args.get("flip"), tc.args.get("empty")
    repo = repo_class(L, t.name)
    hoist = _Hoist()
    over, params, checks, noise = {}, [], [], []
    for i, c in enumerate(q.where):
        col = t.col(c.column)
        a = c.column
        flipped = i == flip
        ln = col.length or 0
        if c.has_value:
            lit = _cs_value(col, c.value)
            outside, inside = f"x.{a} = Different({lit}, {ln});", f"x.{a} = {lit};"
            if c.op == "ne":
                outside, inside = inside, outside
            put_over(over, c.column, outside if flipped else inside, 3 if flipped else 2)
            noise.append(outside)
            checks.append(_check(a, c.op, lit))
            continue
        if c.op in ("is_null", "not_null"):
            want_null = (c.op == "is_null") != flipped
            sample = hoist(_sample(t, c.column, tables))
            put_over(over, c.column, f"x.{a} = null;" if want_null else f"x.{a} = {sample};", 3 if flipped else 2)
            noise.append(f"x.{a} = null;" if c.op == "not_null" else f"x.{a} = {hoist(_sample(t, c.column, tables))};")
            checks.append(_check(a, c.op, None))
            continue
        if col.nullable:
            put_over(over, c.column, f"x.{a} = {hoist(_sample(t, c.column, tables))};", 1)
        pn = c.param[:1].lower() + c.param[1:]
        ct = CS_TYPE[col.type]
        v = f"(({ct})e.{a}!)"
        if c.column in nulled_columns(q, flip):  # la colonna è vuota nel record: il parametro usa un valore di esempio
            v = f"(({ct})({_sample(t, c.column, tables)}))"
        expr = {
            "eq": f"Different({v}, {ln})" if flipped else v,
            "ne": v if flipped else f"Different({v}, {ln})",
            "gte": f"Greater({v})" if flipped else v,
            "lte": f"Smaller({v})" if flipped else v,
            "gt": v if flipped else f"Smaller({v})",
            "lt": v if flipped else f"Greater({v})",
            "in": f"new[] {{ Different({v}, {ln}) }}" if flipped else f"new List<{ct}> {{ {v} }}",
            "prefix": '"zz"' if flipped else f"{v}.ToString()!.Substring(0, 1)",
        }[c.op]
        if i == empty:
            expr = f"Array.Empty<{ct}>()"
        params.append((f"IReadOnlyCollection<{ct}>" if c.op == "in" else ct, pn, expr))
        checks.append(_check(a, c.op, pn))
    lines = list(hoist.lines)
    over = over_values(over)
    lines.append(f"        var e = await Build{t.name}(db, x => {{ {' '.join(over)} }});" if over else f"        var e = await Build{t.name}(db);")
    if flip is None and empty is None and noise:
        lines.append(f"        await Build{t.name}(db, x => {{ {' '.join(noise)} }}); // fuori dalla classe: non deve comparire")
    for ct, pn, expr in params:
        lines.append(f"        {ct} {pn} = {expr};")
    args = ", ".join(pn for _, pn, _ in params)
    meth = method_name(L, {"page": "query_page", "list": "query_list", "one": "query_one"}[q.returns] + ":" + q.name)
    if q.returns == "page":
        lines.append(f"        var rows = (await new {repo}(db).{meth}({args + ', ' if args else ''}new PageRequest({t.pagination.max_limit}))).Items;")
    elif q.returns == "list":
        lines.append(f"        var rows = await new {repo}(db).{meth}({args});")
    else:
        lines.append(f"        var one = await new {repo}(db).{meth}({args});")
        lines.append(f"        var rows = one is null ? new List<{t.name}>() : new List<{t.name}> {{ one }};")
    pk = t.pk.name
    if empty is not None:
        lines.append("        Assert.Empty(rows);")
    elif flip is None:
        lines.append(f"        Assert.Contains(rows, x => x.{pk} == e.{pk});")
        lines.append(f'        Assert.All(rows, x => Assert.True({" && ".join("(" + c + ")" for c in checks)}, "un record restituito non soddisfa le condizioni"));')
    else:
        lines.append(f"        Assert.DoesNotContain(rows, x => x.{pk} == e.{pk}); // la condizione {flip + 1} determina da sola l'esito")
    return lines


def _walk(n: str, repo: str, pk: str, sort_expr: str, collect: str = "") -> List[str]:
    return ["        string? cursor = null;", "        for (var i = 0; i < 100; i++)", "        {",
            f"            var page = await repo.ListPageAsync(new PageRequest(1, cursor, {sort_expr}));",
            "            foreach (var x in page.Items)", "            {", f"                seen.Add(x.{pk});",
            *([collect] if collect else []), "            }", "            if (!page.HasMore) break;", "            cursor = page.NextCursor;", "        }"]


def _fact(tc: TestCase) -> List[str]:
    return ["", f"    [Fact(DisplayName = {_cs(tc.id + ' · ' + ', '.join(tc.reqs) + ' · ' + METHODS[tc.method] + ': ' + tc.title)})]",
            f"    public async Task {tc.slug}()", "    {", f"        // atteso: {tc.expected}"]


def test_file(ns: str, t: Table, cat: Catalog, tables: Dict[str, Table], default_asil: str) -> str:
    n = t.name
    repo = repo_class(L, n)
    pk = t.pk.name
    o = [header(L, f"schemas/db/{n}.yaml") + "// <auto-generated />", "#nullable enable", *USINGS, f"using {ns};",
         f"using static {_ns(ns)}.KybesBuilders;", "", f"namespace {_ns(ns)};", "",
         f"/// <summary>Test di unità generati per {n} (ASIL {table_asil(t, default_asil)}). Specifica: docs/generated/verification/{n}.md."
         " I test dei metodi custom vanno in tests/custom/.</summary>",
         f"public sealed class {n}Tests : IDisposable", "{", "    private readonly AppDbContext db = KybesDb.Open();", "",
         "    public void Dispose() => db.Dispose();"]
    compare = [c.name for c in t.columns if c.type != "json" and not c.generated]
    for tc in cat.for_table(n):
        o += _fact(tc)
        k = tc.kind
        b = f"Build{n}"
        if t.mongo and k in ("unique_duplicate", "tenant_required", "generated_values") or k.startswith("mongo_"):
            o += _mongo_case(t, tc, tables)
        elif k == "create_valid":
            o += [f"        var e = await {b}(db);", "        using var check = KybesDb.NewContext();",
                  f"        var got = await new {repo}(check).GetByIdAsync(e.{pk});", "        Assert.NotNull(got);"]
            o += [f'        Assert.True(Cmp(got!.{cn}, e.{cn}) == 0, "{cn}");' for cn in compare]
        elif k == "read_existing":
            o += [f"        var e = await {b}(db);", f"        var repo = new {repo}(db);", f"        Assert.Equal(e.{pk}, (await repo.GetByIdAsync(e.{pk}))!.{pk});",
                  f"        Assert.True(await repo.ExistsAsync(e.{pk}));", "        Assert.True(await repo.CountAsync() >= 1);"]
        elif k == "read_missing":
            o += [f"        var repo = new {repo}(db);", f"        Assert.Null(await repo.GetByIdAsync({_missing_pk(t)}));",
                  f"        Assert.False(await repo.ExistsAsync({_missing_pk(t)}));"]
        elif k == "update_allowed":
            cn = tc.args["column"]
            o += [f"        var e = await {b}(db);", f"        var value = {_new_value(t, cn)};", f"        e.{cn} = value;",
                  f"        await new {repo}(db).UpdateAsync(e);", "        using var check = KybesDb.NewContext();",
                  f"        Assert.Equal(0, Cmp((await new {repo}(check).GetByIdAsync(e.{pk}))!.{cn}, value));"]
        elif k == "update_missing":
            o += [f"        var e = await {b}(db);", f"        var repo = new {repo}(db);", f"        Assert.True(await repo.DeleteAsync(e.{pk}));",
                  "        var before = await repo.CountAsync();", "        await Assert.ThrowsAsync<KeyNotFoundException>(() => repo.UpdateAsync(e));",
                  "        using var check = KybesDb.NewContext();", f"        Assert.Null(await new {repo}(check).GetByIdAsync(e.{pk}));",
                  f"        Assert.Equal(before, await new {repo}(check).CountAsync());"]
        elif k == "update_key":
            o += [f"        var e = await {b}(db);", f"        var original = e.{pk};", "        db.ChangeTracker.Clear();",
                  f"        e.{pk} = {_missing_pk(t)};", f"        await Assert.ThrowsAsync<KeyNotFoundException>(() => new {repo}(db).UpdateAsync(e));",
                  "        using var check = KybesDb.NewContext();", f"        Assert.True(await new {repo}(check).ExistsAsync(original));",
                  f"        await Assert.ThrowsAsync<ArgumentException>(() => new {repo}(db).UpdateAsync(new {n}()));",
                  f"        Assert.False(await new {repo}(check).ExistsAsync({_missing_pk(t)}));"]
        elif k == "delete":
            o += [f"        var e = await {b}(db);", f"        var repo = new {repo}(db);", f"        Assert.True(await repo.DeleteAsync(e.{pk}));",
                  f"        Assert.Null(await repo.GetByIdAsync(e.{pk}));", f"        Assert.False(await repo.DeleteAsync(e.{pk}));"]
        elif k == "find_by":
            cn = tc.args["column"]
            meth = method_name(L, "find_by:" + cn)
            ct = CS_TYPE[t.col(cn).type]
            o += [f"        var e = await {b}(db);", f"        var repo = new {repo}(db);",
                  f"        Assert.Equal(e.{pk}, (await repo.{meth}(e.{cn}!))!.{pk});",
                  f"        Assert.Null(await repo.{meth}(Different(({ct})e.{cn}!, {t.col(cn).length or 0})));"]
        elif k == "required_null":
            cn = tc.args["column"]
            c = t.col(cn)
            rel = next((r for r in t.relations if r.kind == "many_to_one" and r.foreign_key == cn), None)
            if c.type in REF_TYPES:
                o += [f'        await KybesDb.AssertRule("{cn}", "obbligatorio", () => {b}(db, x => x.{cn} = null!));']
            elif rel:
                empty = "Guid.Empty" if c.type == "uuid" else ("0L" if c.type == "bigint" else "0")
