_TC = ["Guid"]


def _tval(which: str) -> str:
    return f'Guid.Parse("00000000-0000-4000-8000-00000000000{which}")' if _TC[0] == "Guid" else f'"tenant-{which}"'


def _cs(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def _ns(ns: str) -> str:
    return ns + ".Tests"


def _sample(t: Table, cn: str, tables: Dict[str, Table]) -> str:
    """Espressione C# per un valore valido; le chiavi esterne richiedono un await (vedi _hoist)."""
    c = t.col(cn)
    rel = next((r for r in t.relations if r.kind == "many_to_one" and r.foreign_key == cn), None)
    if rel:
        return f"(await Build{rel.target}(db)).{tables[rel.target].pk.name}"
    if cn == ttl_column(t):
        return {"date": "DateOnly.FromDateTime(DateTime.UtcNow).AddDays(NextN())", "datetime": "new DateTimeOffset(DateTime.UtcNow.Date, TimeSpan.Zero).AddDays(1).AddHours(NextN())"}[c.type]
    if c.type == "string":
        return f"TextValue(NextN(), {c.length})"
    return {"uuid": "Guid.NewGuid()", "text": '$"testo {NextN()}"', "int": "NextN()", "bigint": "(long)NextN()",
            "decimal": "NextN() + 0.50m", "bool": "true", "date": "new DateOnly(2026, 1, 1).AddDays(NextN())",
            "datetime": "new DateTimeOffset(2026, 1, 1, 0, 0, 0, TimeSpan.Zero).AddHours(NextN())",
            "json": '$"{{\\"n\\": {NextN()}}}"'}[c.type]


class _Hoist:
    """Raccoglie i valori che richiedono un await, da calcolare prima delle lambda dei builder."""

    def __init__(self) -> None:
        self.lines: List[str] = []

    def __call__(self, expr: str) -> str:
        if "await " not in expr:
            return expr
        name = f"s{len(self.lines) + 1}"
        self.lines.append(f"        var {name} = {expr};")
        return name


def _missing_pk(t: Table) -> str:
    return {"uuid": 'Guid.Parse("00000000-0000-4000-8000-000000000999")', "int": "987654321", "bigint": "987654321L",
            "string": '"kybes-non-esiste"'}[t.pk.type]


def _new_value(t: Table, cn: str) -> str:
    c = t.col(cn)
    if c.type == "string":
        return f'"u" + TextValue(NextN(), {max(c.length - 1, 1)})'
    return {"text": '"testo aggiornato"', "int": "NextN() + 500", "bigint": "NextN() + 500L", "decimal": "99.25m"}[c.type]


