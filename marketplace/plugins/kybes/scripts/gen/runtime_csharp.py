"""Classi di supporto C# generate: paginazione a cursore e Unit of Work."""
from __future__ import annotations

from typing import Dict

from naming import header
from schema import Table


def paging_file(ns: str) -> str:
    return header("csharp", "kit") + "// <auto-generated />\n#nullable enable\n" + PAGING_USINGS + f"\nnamespace {ns};\n" + PAGING


PAGING_USINGS = """using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Linq.Expressions;
using System.Reflection;
using System.Text;
using System.Text.Json;
using System.Threading;
using System.Threading.Tasks;
using Microsoft.EntityFrameworkCore;
"""

PAGING = r'''
/// <summary>Richiesta di pagina: Sort usa i nomi JSON (camelCase), con "-" per l'ordine discendente.</summary>
public sealed record PageRequest(int? Limit = null, string? Cursor = null, string? Sort = null)
{
    public static PageRequest First { get; } = new();

    public PageRequest Next(string? nextCursor) => this with { Cursor = nextCursor };
}

public sealed record Page<T>(IReadOnlyList<T> Items, string? NextCursor, int Limit)
{
    public bool HasMore => NextCursor is not null;
}

public enum SortType { Uuid, String, Int, BigInt, Decimal, Date, DateTime }

/// <summary>Prop: proprietà C#; Json: nome nel contratto API.</summary>
public sealed record OrderItem(string Prop, string Json, SortType Type, bool Desc);

public sealed record PagingSpec(string Table, OrderItem Pk, IReadOnlyDictionary<string, OrderItem> Sortable,
    IReadOnlyList<OrderItem> DefaultOrder, int DefaultLimit, int MaxLimit);

/// <summary>
/// Paginazione a cursore (keyset), uguale per UI, API e DB-Model.
/// Il cursore è opaco: base64url di {"s": ordinamento, "v": [valori dell'ultima riga]}, come negli altri linguaggi.
/// </summary>
public static class Paging
{
    public static string LikePrefix(string value) =>
        value.Replace("\\", "\\\\").Replace("%", "\\%").Replace("_", "\\_") + "%";

    private static ModelValidationException Invalid(PagingSpec spec, string key, string rule) =>
        new ModelValidationException(spec.Table, new Dictionary<string, string> { [key] = rule });

    public static List<OrderItem> ResolveOrder(PagingSpec spec, string? sort)
    {
        if (string.IsNullOrWhiteSpace(sort)) return spec.DefaultOrder.ToList();
        var order = new List<OrderItem>();
        foreach (var raw in sort.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
        {
            var desc = raw[0] == '-';
            var name = raw[0] is '-' or '+' ? raw[1..] : raw;
            OrderItem? col = name == spec.Pk.Json ? spec.Pk : spec.Sortable.GetValueOrDefault(name);
            if (col is null) throw Invalid(spec, "sort", "colonna non ordinabile: " + name);
            order.Add(col with { Desc = desc });
        }
        if (!order.Any(o => o.Prop == spec.Pk.Prop)) order.Add(spec.Pk);
        return order;
    }

    private static string Signature(IReadOnlyList<OrderItem> order) =>
        string.Join(",", order.Select(o => (o.Desc ? "-" : "") + o.Json));

    private static object Encode(object value, SortType type) => type switch
    {
        SortType.Int => Convert.ToInt32(value, CultureInfo.InvariantCulture),
        SortType.Decimal => ((decimal)value).ToString(CultureInfo.InvariantCulture),
        SortType.Date => ((DateOnly)value).ToString("yyyy-MM-dd", CultureInfo.InvariantCulture),
        SortType.DateTime => ((DateTimeOffset)value).ToString("O", CultureInfo.InvariantCulture),
        SortType.BigInt => Convert.ToInt64(value, CultureInfo.InvariantCulture).ToString(CultureInfo.InvariantCulture),
        _ => Convert.ToString(value, CultureInfo.InvariantCulture) ?? "",
    };

    private static object Decode(JsonElement v, SortType type)
    {
        if (type == SortType.Int)
        {
            if (v.ValueKind != JsonValueKind.Number || !v.TryGetInt32(out var i)) throw new FormatException("intero atteso");
            return i;
        }
        if (v.ValueKind != JsonValueKind.String) throw new FormatException("stringa attesa");
        var s = v.GetString()!;
        return type switch
        {
            SortType.Uuid => Guid.Parse(s),
            SortType.BigInt => long.Parse(s, CultureInfo.InvariantCulture),
            SortType.Decimal => decimal.Parse(s, NumberStyles.Number, CultureInfo.InvariantCulture),
            SortType.Date => DateOnly.ParseExact(s, "yyyy-MM-dd", CultureInfo.InvariantCulture),
            SortType.DateTime => DateTimeOffset.Parse(s, CultureInfo.InvariantCulture, DateTimeStyles.RoundtripKind),
            _ => s,
        };
    }

    private static object ValueOf(object row, string prop) =>
        row.GetType().GetProperty(prop, BindingFlags.Public | BindingFlags.Instance)!.GetValue(row)
        ?? throw new InvalidOperationException("colonna di ordinamento nulla: " + prop);

    public static string EncodeCursor(IReadOnlyList<OrderItem> order, object row)
    {
        var payload = new Dictionary<string, object>
        {
            ["s"] = Signature(order),
            ["v"] = order.Select(o => Encode(ValueOf(row, o.Prop), o.Type)).ToArray(),
        };
        var bytes = JsonSerializer.SerializeToUtf8Bytes(payload);
        return Convert.ToBase64String(bytes).TrimEnd('=').Replace('+', '-').Replace('/', '_');
    }

    public static IReadOnlyList<object> DecodeCursor(PagingSpec spec, IReadOnlyList<OrderItem> order, string cursor)
    {
        try
        {
            var b64 = cursor.Replace('-', '+').Replace('_', '/');
            b64 = b64.PadRight(b64.Length + (4 - b64.Length % 4) % 4, '=');
            using var doc = JsonDocument.Parse(Convert.FromBase64String(b64));
            var root = doc.RootElement;
            if (root.GetProperty("s").GetString() != Signature(order)) throw new FormatException("ordinamento diverso");
            var values = root.GetProperty("v");
            if (values.GetArrayLength() != order.Count) throw new FormatException("numero di valori");
            return order.Select((o, i) => Decode(values[i], o.Type)).ToList();
        }
        catch (Exception e) when (e is FormatException or JsonException or KeyNotFoundException or InvalidOperationException
                                      or OverflowException or ArgumentException)
        {
            throw Invalid(spec, "cursor", "non valido");
        }
    }

    // valore incapsulato: EF lo traduce in un parametro SQL invece di una costante
    private sealed class Box
    {
        public Box(object value) { Value = value; }
        public object Value { get; }
    }

    private static Expression Param(object value, Type type) =>
        Expression.Convert(Expression.Property(Expression.Constant(new Box(value)), nameof(Box.Value)), type);

    public static IQueryable<T> OrderRows<T>(IQueryable<T> query, IReadOnlyList<OrderItem> order)
    {
        var expr = query.Expression;
        for (var i = 0; i < order.Count; i++)
        {
            var p = Expression.Parameter(typeof(T), "x");
            var body = Expression.Property(p, order[i].Prop);
            var lambda = Expression.Lambda(body, p);
            var method = i == 0 ? (order[i].Desc ? "OrderByDescending" : "OrderBy") : (order[i].Desc ? "ThenByDescending" : "ThenBy");
            expr = Expression.Call(typeof(Queryable), method, new[] { typeof(T), body.Type }, expr, Expression.Quote(lambda));
        }
        return query.Provider.CreateQuery<T>(expr);
    }

    /// <summary>(a, b, c) &gt; (x, y, z) espanso colonna per colonna; il confronto usa CompareTo, tradotto da EF Core.</summary>
    private static Expression<Func<T, bool>> After<T>(IReadOnlyList<OrderItem> order, IReadOnlyList<object> values)
    {
        var p = Expression.Parameter(typeof(T), "x");
        Expression? any = null;
        for (var i = 0; i < order.Count; i++)
        {
            Expression? branch = null;
            for (var j = 0; j < i; j++)
            {
                var m = Expression.Property(p, order[j].Prop);
                var eq = Expression.Equal(m, Param(values[j], m.Type));
                branch = branch is null ? eq : Expression.AndAlso(branch, eq);
            }
            var col = Expression.Property(p, order[i].Prop);
            var compareTo = col.Type.GetMethod("CompareTo", new[] { col.Type })!;
            var cmp = Expression.Call(col, compareTo, Param(values[i], col.Type));
            Expression step = order[i].Desc
                ? Expression.LessThan(cmp, Expression.Constant(0))
                : Expression.GreaterThan(cmp, Expression.Constant(0));
            branch = branch is null ? step : Expression.AndAlso(branch, step);
            any = any is null ? branch : Expression.OrElse(any, branch);
        }
        return Expression.Lambda<Func<T, bool>>(any!, p);
    }

    public static async Task<Page<T>> RunPageAsync<T>(IQueryable<T> query, PagingSpec spec, PageRequest? page,
        IReadOnlyList<OrderItem>? fixedOrder = null, CancellationToken ct = default) where T : class
    {
        page ??= PageRequest.First;
        if (fixedOrder is not null && !string.IsNullOrWhiteSpace(page.Sort))
            throw Invalid(spec, "sort", "questa query ha un ordinamento fisso");
        var order = fixedOrder?.ToList() ?? ResolveOrder(spec, page.Sort);
        var limit = page.Limit ?? spec.DefaultLimit;
        if (limit < 1 || limit > spec.MaxLimit) throw Invalid(spec, "limit", $"tra 1 e {spec.MaxLimit}");
        if (!string.IsNullOrEmpty(page.Cursor)) query = query.Where(After<T>(order, DecodeCursor(spec, order, page.Cursor)));
        var rows = await OrderRows(query, order).Take(limit + 1).ToListAsync(ct);
        var more = rows.Count > limit;
        var items = more ? rows.GetRange(0, limit) : rows;
        return new Page<T>(items, more && items.Count > 0 ? EncodeCursor(order, items[^1]) : null, limit);
    }

    public static Page<T> EmptyPage<T>(PagingSpec spec, PageRequest? page) =>
        new(Array.Empty<T>(), null, page?.Limit ?? spec.DefaultLimit);
}
'''


def uow_file(ns: str, tables: Dict[str, Table]) -> str:
    level = {"read_committed": "ReadCommitted", "repeatable_read": "RepeatableRead", "serializable": "Serializable"}
    entries = "\n".join(f'        ["{n}"] = IsolationLevel.{level[t.isolation]},' for n, t in tables.items())
    return header("csharp", "kit") + "// <auto-generated />\n" + f'''#nullable enable
using System;
using System.Collections.Generic;
using System.Data;
using System.Data.Common;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Microsoft.EntityFrameworkCore;

namespace {ns};

/// <summary>
/// Unit of Work: transazioni aperte dal service, con isolamento e retry sui conflitti.
/// <code>
/// var id = await UnitOfWork.RunAsync(db, async (ctx, ct) =&gt; {{
///     var ordini = new OrdiniRepository(ctx);
///     ...
/// }}, new[] {{ "Ordini", "RigheOrdine" }});
/// </code>
/// Funziona anche con una execution strategy che ritenta (EnableRetryOnFailure): l'intero blocco viene ripetuto.
/// </summary>
public static class UnitOfWork
{{
    /// <summary>Livello di isolamento dichiarato negli schemi (transactions.isolation).</summary>
    public static readonly IReadOnlyDictionary<string, IsolationLevel> Isolation = new Dictionary<string, IsolationLevel>
    {{
{entries}
    }};

    private static readonly IsolationLevel[] Rank = {{ IsolationLevel.ReadCommitted, IsolationLevel.RepeatableRead, IsolationLevel.Serializable }};

    /// <summary>SQLSTATE ritentabili: conflitto di serializzazione e deadlock.</summary>
    public static readonly IReadOnlySet<string> RetryableSqlState = new HashSet<string> {{ "40001", "40P01" }};

    public static IsolationLevel IsolationFor(IEnumerable<string> tables)
    {{
        var best = 0;
        foreach (var t in tables)
        {{
            var level = Isolation.TryGetValue(t, out var l) ? Array.IndexOf(Rank, l) : 0;
            if (level > best) best = level;
        }}
        return Rank[best];
    }}

    public static bool IsRetryable(Exception error)
    {{
        for (Exception? e = error; e is not null; e = e.InnerException)
        {{
            if (e is DbException db && db.SqlState is not null && RetryableSqlState.Contains(db.SqlState)) return true;
        }}
        return false;
    }}

    /// <summary>Esegue work in una transazione; la ripete da capo sui conflitti di serializzazione e sui deadlock.</summary>
    public static Task<T> RunAsync<T>(AppDbContext db, Func<AppDbContext, CancellationToken, Task<T>> work,
        IEnumerable<string>? tables = null, IsolationLevel? isolation = null, int maxRetries = 3, int backoffMs = 50,
        object? tenant = null, CancellationToken ct = default)
    {{
        var level = isolation ?? IsolationFor(tables ?? Array.Empty<string>());
        var strategy = db.Database.CreateExecutionStrategy();
        return strategy.ExecuteAsync(async () =>
        {{
            for (var attempt = 0; ; attempt++)
            {{
                await using var tx = await db.Database.BeginTransactionAsync(level, ct);
                try
                {{
                    if (tenant is not null)
                    {{
                        db.BindTenant(tenant);
                        await Tenancy.ApplySettingAsync(db, ct); // PostgreSQL: app.tenant_id per la transazione
                    }}
                    var result = await work(db, ct);
                    await tx.CommitAsync(ct);
                    return result;
                }}
                catch (Exception e) when (attempt < maxRetries && IsRetryable(e))
                {{
                    // con SERIALIZABLE il conflitto arriva spesso al COMMIT: la transazione può essere già chiusa
                    try {{ await tx.RollbackAsync(CancellationToken.None); }} catch (InvalidOperationException) {{ }}
                    db.ChangeTracker.Clear();
                    await Task.Delay(backoffMs * (1 << attempt), ct);
                }}
            }}
        }});
    }}
}}
'''
