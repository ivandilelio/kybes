"""Nomi di file e metodi per linguaggio: un'unica tabella di corrispondenza per tutto il kit."""
from __future__ import annotations

from typing import Dict

from schema import camel, snake

LANGS = ("python", "typescript", "csharp", "java")
EXT = {"python": ".py", "typescript": ".ts", "csharp": ".cs", "java": ".java"}
MARKER = "AUTO-GENERATED by kybes"
GEN_DIR = "generated"


def custom_file(lang: str, table: str) -> str:
    """Nome del file custom (punto d'ingresso) nella cartella model."""
    return f"{table}Repository.java" if lang == "java" else f"{table}{EXT[lang]}"


def repo_class(lang: str, table: str) -> str:
    return f"{table}Repository"


def base_class(lang: str, table: str) -> str:
    # in C# la classe generata e quella custom sono la stessa partial class
    return f"{table}Repository" if lang == "csharp" else f"{table}RepositoryBase"


def method_name(lang: str, key: str) -> str:
    kind, _, arg = key.partition(":")
    if lang == "python":
        return {"get_by_id": "get_by_id", "count": "count", "exists": "exists",
                "create": "create", "update": "update", "delete": "delete",
                "find_by": f"find_by_{snake(arg)}", "list_by": f"list_by_{snake(arg)}",
                "get_rel": f"get_{snake(arg)}", "list_rel": f"list_{snake(arg)}",
                "list_page": "list_page", "list_page_expand": "list_page_expand",
                "query_page": f"list_{snake(arg)}", "query_list": f"list_{snake(arg)}",
                "query_one": f"find_{snake(arg)}"}[kind]
    base = {"get_by_id": "getById", "count": "count", "exists": "exists",
            "create": "create", "update": "update", "delete": "delete",
            "find_by": f"findBy{arg}", "list_by": f"listBy{arg}",
            "get_rel": f"get{arg}", "list_rel": f"list{arg}",
            "list_page": "listPage", "list_page_expand": "listPageExpand",
            "query_page": f"list{arg}", "query_list": f"list{arg}",
            "query_one": f"find{arg}"}[kind]
    if lang == "csharp":
        return base[:1].upper() + base[1:] + "Async"
    return base


def member(lang: str, name: str) -> str:
    """Nome di colonna/relazione come membro della classe."""
    if lang == "python":
        return snake(name)
    if lang == "csharp":
        return name
    return camel(name)


def header(lang: str, source: str) -> str:
    c = "#" if lang == "python" else "//"
    return (f"{c} {MARKER}. NON MODIFICARE: questo file viene rigenerato.\n"
            f"{c} Sorgente: {source}. Per cambiare la tabella modifica lo schema; per i metodi custom usa il file in model/.\n")


def gen_options(target: Dict) -> Dict:
    return {
        "namespace": target.get("namespace", "App.Model"),
        "package": target.get("package", "app.model"),
        "dialect": target.get("dialect", "postgres"),
    }
