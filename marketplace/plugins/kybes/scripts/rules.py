CS_ORM = re.compile(r"^\s*using\s+(?:static\s+)?(?:Microsoft\.EntityFrameworkCore|Dapper|Npgsql|MySqlConnector|MySql\.Data|Microsoft\.Data\.SqlClient|System\.Data\.SqlClient|Microsoft\.Data\.Sqlite|MongoDB\.Driver|NHibernate|LinqToDB)\b", re.M)
JAVA_ORM = re.compile(r"^\s*import\s+(?:static\s+)?(?:jakarta\.persistence|javax\.persistence|java\.sql|javax\.sql|org\.hibernate|org\.springframework\.jdbc|org\.springframework\.data\.jpa|org\.jooq|org\.mybatis|com\.mongodb)\b", re.M)


@dataclass
class Finding:
    rule: str
    severity: str  # "block" | "warn"
    path: str
    line: int
    message: str

    def format(self) -> str:
        loc = f"{self.path}:{self.line}" if self.line else self.path
        tag = "BLOCCANTE" if self.severity == "block" else "AVVISO"
        return f"[{tag}] {self.rule} - {loc} - {self.message}"


# ---------------------------------------------------------------- config

def find_project_dir(start: Optional[str] = None) -> Path:
    env = os.environ.get("CLAUDE_PROJECT_DIR")
    if env:
        return Path(env).resolve()
    p = Path(start or os.getcwd()).resolve()
    for cand in [p, *p.parents]:
        if (cand / CONFIG_REL).exists():
            return cand
    return p


def _merge(base: dict, over: dict) -> dict:
    out = dict(base)
    for k, v in over.items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = _merge(out[k], v)
        else:
            out[k] = v
    return out


def load_config(project_dir: Path) -> Optional[dict]:
    """Restituisce None se il progetto non usa il kit (nessun file di config)."""
    path = project_dir / CONFIG_REL
    if not path.exists():
        return None
    try:
        user = json.loads(path.read_text(encoding="utf-8"))
    except Exception as exc:  # config rotta: meglio fermarsi con un messaggio chiaro
        raise SystemExit(f"kybes: {CONFIG_REL} non è JSON valido: {exc}")
    return _merge(DEFAULT_CONFIG, user)


# ---------------------------------------------------------------- glob

_glob_cache: dict = {}


def _glob_to_regex(pattern: str) -> "re.Pattern[str]":
    if pattern in _glob_cache:
        return _glob_cache[pattern]
    i, out = 0, ["^"]
    while i < len(pattern):
        c = pattern[i]
        if pattern.startswith("**/", i):
            out.append(r"(?:.*/)?")
            i += 3
        elif pattern.startswith("**", i):
            out.append(r".*")
            i += 2
        elif c == "*":
            out.append(r"[^/]*")
            i += 1
        elif c == "?":
            out.append(r"[^/]")
            i += 1
        elif c == "{":
            j = pattern.find("}", i)
            if j == -1:
                out.append(re.escape(c))
                i += 1
            else:
                opts = pattern[i + 1:j].split(",")
                out.append("(?:" + "|".join(re.escape(o) for o in opts) + ")")
                i = j + 1
        else:
            out.append(re.escape(c))
            i += 1
    out.append("$")
    rx = re.compile("".join(out))
    _glob_cache[pattern] = rx
    return rx


def matches(rel_path: str, patterns: Iterable[str]) -> bool:
    rel = rel_path.replace(os.sep, "/")
    while rel.startswith("./"):
        rel = rel[2:]
    return any(_glob_to_regex(p).match(rel) for p in patterns)


def rel_to_project(path: str, project_dir: Path) -> Optional[str]:
    p = Path(path)
    if not p.is_absolute():
        p = project_dir / p
    try:
        return p.resolve().relative_to(project_dir).as_posix()
    except ValueError:
        return None  # file fuori dal progetto: non ci riguarda


def model_target_dirs(cfg: dict) -> List[tuple]:
    """[(lang, cartella model)] configurati nella sezione model."""
    return [(t.get("lang"), str(t.get("dir", "")).rstrip("/")) for t in (cfg.get("model") or {}).get("targets", []) if t.get("dir")]


def area_of(rel: str, cfg: dict) -> Optional[str]:
    if any(rel.startswith(d + "/") for _, d in model_target_dirs(cfg)):
        return "db_models"
    for area in ("db_models", "functions", "microservices", "jobs", "utils", "errors", "frontend", "infra"):
        if matches(rel, cfg["paths"].get(area, [])):
            return area
    return None


# ---------------------------------------------------------------- regex

def _orm_regexes(cfg: dict):
    extra_py = [m for m in cfg.get("extra_forbidden_modules", []) if not m.startswith("js:")]
    extra_js = [m[3:] for m in cfg.get("extra_forbidden_modules", []) if m.startswith("js:")]
    py = PY_ORM + ("|" + "|".join(re.escape(m) for m in extra_py) if extra_py else "")
    js = JS_ORM + ("|" + "|".join(re.escape(m) for m in extra_js) if extra_js else "")
    py_rx = re.compile(rf"^\s*(?:from|import)\s+(?:{py})\b", re.M)
    js_rx = re.compile(rf"""(?:from\s+|require\(\s*|import\(\s*|import\s+)['"](?:{js})['"]""")
    return py_rx, js_rx


RAW_SQL = re.compile(r"""['"`][^'"`\n]*\b(?:SELECT\s+[\w*, .]+\s+FROM|INSERT\s+INTO|UPDATE\s+\w+\s+SET|DELETE\s+FROM)\b""", re.I)

SECRET_PATTERNS = [
    (re.compile(r"\bAKIA[0-9A-Z]{16}\b"), "chiave di accesso AWS in chiaro"),
    (re.compile(r"-----BEGIN (?:RSA |EC |DSA |OPENSSH )?PRIVATE KEY-----"), "chiave privata in chiaro"),
    (re.compile(r"\bxox[baprs]-[0-9A-Za-z-]{10,}"), "token Slack in chiaro"),
    (re.compile(r"\bgh[pousr]_[0-9A-Za-z]{30,}"), "token GitHub in chiaro"),
    (re.compile(r"\bsk-[A-Za-z0-9_-]{20,}"), "API key in chiaro"),
    (re.compile(
        r"""(?i)\b(?:password|passwd|pwd|secret|client_secret|api[_-]?key|access[_-]?token|auth[_-]?token)\b["']?\s*[:=]\s*["']([^"'\s]{8,})["']"""),
     "credenziale in chiaro"),
]
SECRET_PLACEHOLDERS = re.compile(r"(?i)^(?:\$\{.*\}|<.*>|\{\{.*\}\}|.*(?:changeme|example|placeholder|dummy|xxxx|your[-_]|test|fake|redacted|\*\*\*).*)$")

PY_LEAK = re.compile(r"""(?:return|jsonify|JSONResponse|HTTPException|Response|body|detail|"message"|'message'|"error"|'error').*(?:\bstr\(\s*(?:e|err|exc|ex|error|exception)\s*\)|traceback\.format_exc|repr\(\s*(?:e|err|exc|ex)\s*\))""")
PY_SWALLOW = re.compile(r"except(?:\s+[\w.]+(?:\s+as\s+\w+)?)?\s*:\s*pass\b")
JS_LEAK = re.compile(r"""(?:res\.\w+\(|ctx\.body|body\s*:|JSON\.stringify\(|reply\.send\(|return\s*\{).*\b(?:e|err|error|ex|exception)\.(?:stack|message)\b""")
JS_SWALLOW = re.compile(r"catch\s*(?:\(\s*\w*\s*\))?\s*\{\s*\}")

UTILS_IMPURE_PY = re.compile(r"^\s*(?:from|import)\s+(?:requests|httpx|urllib3|boto3|botocore|aiohttp|db_models|redis)\b|os\.environ", re.M)
UTILS_IMPURE_JS = re.compile(r"""(?:from\s+|require\(\s*)['"](?:axios|node-fetch|got|undici|@aws-sdk/[\w-]+|aws-sdk|redis|ioredis|@[\w-]+/db-models|db-models)['"]|process\.env|\bfetch\(""")

FN_SLEEP_PY = re.compile(r"(?:time|asyncio)\.sleep\(\s*(?:[1-9]\d+|\d{3,})(?:\.\d+)?\s*\)")
FN_SLEEP_JS = re.compile(r"setTimeout\([^;]*,\s*\d{5,}\s*\)")
FN_SOCKET = re.compile(r"""^\s*(?:from|import)\s+(?:websockets|socketio|flask_socketio)\b|['"](?:ws|socket\.io|socket\.io-client)['"]""", re.M)


def _line_of(text: str, idx: int) -> int:
    return text.count("\n", 0, idx) + 1


def _sev(cfg: dict, rule: str) -> Optional[str]:
    s = cfg["rules"].get(rule, "off")
    return s if s in ("block", "warn") else None


# ---------------------------------------------------------------- check

def check_content(rel: str, content: str, cfg: dict) -> List[Finding]:
    """Controlla un frammento o un file intero che verrà scritto in `rel`."""
    out: List[Finding] = []
    if matches(rel, cfg["paths"].get("ignore", [])):
        return out
    ext = Path(rel).suffix.lower()
    name = Path(rel).name.lower()
    is_code = ext in CODE_EXT
    is_py = ext == ".py"
    area = area_of(rel, cfg)
    in_models = area == "db_models"
    is_test = bool(re.search(r"(^|/)(tests?|__tests__)/|(_test|\.test|\.spec|_spec)\.\w+$|(^|/)test_[^/]+$", rel))

    # 1. ORM / driver DB fuori da DB-Models
    sev = _sev(cfg, "orm_outside_db_models")
    if sev and is_code and not in_models:
        py_rx, js_rx = _orm_regexes(cfg)
        rx = {".py": py_rx, ".cs": CS_ORM, ".java": JAVA_ORM}.get(ext, js_rx)
        for m in rx.finditer(content):
            out.append(Finding("orm_outside_db_models", sev, rel, _line_of(content, m.start()),
                               f"import di ORM/driver DB fuori da DB-Models ('{m.group(0).strip()}'). "
                               "Sposta la logica di persistenza in libs/db-models e importa da lì."))

    # 2. SQL scritto a mano fuori da DB-Models
    sev = _sev(cfg, "raw_sql_outside_db_models")
    if sev and is_code and not in_models and not is_test and area in ("functions", "microservices", "jobs", "utils"):
        for m in RAW_SQL.finditer(content):
            out.append(Finding("raw_sql_outside_db_models", sev, rel, _line_of(content, m.start()),
                               "SQL scritto a mano fuori da DB-Models: aggiungi un metodo al repository in libs/db-models."))

    # 3. segreti in chiaro (ovunque, tranne file di esempio)
    sev = _sev(cfg, "hardcoded_secrets")
    if sev and (ext in TEXT_EXT or name.startswith(".env")) and not re.search(r"\.(example|sample|template)(\.|$)", name) and not is_test:
        for rx, label in SECRET_PATTERNS:
            for m in rx.finditer(content):
                val = m.group(1) if m.groups() else m.group(0)
                if SECRET_PLACEHOLDERS.match(val or ""):
                    continue
                out.append(Finding("hardcoded_secrets", sev, rel, _line_of(content, m.start()),
                                   f"{label}: usa Secrets Manager / Parameter Store o variabili d'ambiente iniettate dall'IaC."))

    # 4. fuoriuscita di dettagli interni negli errori
    sev = _sev(cfg, "error_leak")
    if sev and is_code and area in ("functions", "microservices", "jobs") and not is_test:
        leak, swallow = (PY_LEAK, PY_SWALLOW) if is_py else (JS_LEAK, JS_SWALLOW)
        for m in leak.finditer(content):
            out.append(Finding("error_leak", sev, rel, _line_of(content, m.start()),
                               "possibile esposizione di dettagli interni (messaggio di eccezione o stack) nella risposta: "
                               "usa il modulo libs/errors (codice + messaggio generico + correlationId)."))
        for m in swallow.finditer(content):
            out.append(Finding("error_leak", sev, rel, _line_of(content, m.start()),
                               "eccezione ignorata in silenzio: gestiscila con libs/errors (rollback / accodamento / log)."))

    # 5. Utils deve restare pura
    sev = _sev(cfg, "utils_impure")
    if sev and is_code and area == "utils" and not is_test:
        rx = UTILS_IMPURE_PY if is_py else UTILS_IMPURE_JS
        for m in rx.finditer(content):
            out.append(Finding("utils_impure", sev, rel, _line_of(content, m.start()),
                               "libs/utils deve contenere solo funzioni pure (niente rete, DB, AWS, variabili d'ambiente)."))

    # 6. function che non dovrebbero essere function
    sev = _sev(cfg, "function_long_running")
    if sev and is_code and area == "functions" and not is_test:
        for rx in ((FN_SLEEP_PY,) if is_py else (FN_SLEEP_JS,)) + (FN_SOCKET,):
            for m in rx.finditer(content):
                out.append(Finding("function_long_running", sev, rel, _line_of(content, m.start()),
                                   "attese lunghe o WebSocket in una function: oltre 10 s o connessioni persistenti "
                                   "vanno su microservizio Kubernetes; trigger/schedule vanno in un Job."))
    return out


def check_protected(rel: str, cfg: dict) -> List[Finding]:
    sev = _sev(cfg, "protected_paths")
    if sev and matches(rel, cfg["paths"].get("protected", [])):
        return [Finding("protected_paths", sev, rel, 0,
                        "file del kit di controllo: non va modificato dall'agente. Chiedi all'utente di cambiarlo a mano.")]
    return []


def iter_project_files(project_dir: Path, cfg: dict):
    ignore = cfg["paths"].get("ignore", [])
    for root, dirs, files in os.walk(project_dir):
        rel_root = Path(root).relative_to(project_dir).as_posix()
        rel_root = "" if rel_root == "." else rel_root + "/"
        dirs[:] = [d for d in dirs if not matches(rel_root + d + "/x", ignore) and d != ".git"]
        for f in files:
            rel = rel_root + f
            if matches(rel, ignore):
                continue
            ext = Path(f).suffix.lower()
            if ext in TEXT_EXT or f.lower().startswith(".env"):
                yield rel


# ---------------------------------------------------------------- codice duplicato

_SKIP_LINE = re.compile(r"^(?:#|//|/\*|\*|\*/|///|import\s|from\s+\S+\s+import\s|using\s|package\s|export\s+\{|export\s+type\s+\{|export\s+\*|@\w+\s*$|\}?\s*(?:else|finally)?\s*\{?\s*$|[\]\[(){};,]+$|\"\"\"|\'\'\')")
_TEST_RX = re.compile(r"(^|/)(tests?|__tests__)/|(_test|\.test|\.spec|_spec|Tests?)\.\w+$|(^|/)test_[^/]+$")


def _normalized(text: str):
    out = []
    for n, raw in enumerate(text.splitlines(), 1):
        s = raw.strip()
        if not s or _SKIP_LINE.match(s):
            continue
        out.append((n, re.sub(r"\s+", " ", s)))
    return out


def find_duplicates(files: dict, cfg: dict) -> List[Finding]:
    """files: {rel: testo}. Trova blocchi di almeno min_lines righe significative ripetuti."""
    sev = _sev(cfg, "duplicate_code")
    if not sev:
        return []
    dcfg = cfg.get("duplicates") or {}
    n = max(3, int(dcfg.get("min_lines", 8)))
    ignore = list(dcfg.get("ignore") or [])
    include_tests = bool(dcfg.get("include_tests", False))
    import hashlib
    index = {}
    norm = {}
    for rel, text in files.items():
        if Path(rel).suffix.lower() not in CODE_EXT or GENERATED_MARKER in text[:600]:
            continue
        if (ignore and matches(rel, ignore)) or (not include_tests and _TEST_RX.search(rel)):
            continue
        lines = _normalized(text)
        norm[rel] = lines
        for i in range(len(lines) - n + 1):
            h = hashlib.sha1("\n".join(x[1] for x in lines[i:i + n]).encode()).hexdigest()
            index.setdefault(h, []).append((rel, i))
    out: List[Finding] = []
    seen = set()
    last = {}
    for h, occ in index.items():
        if len(occ) < 2:
            continue
        first = occ[0]
        for other in occ[1:]:
            if other[0] == first[0] and abs(other[1] - first[1]) < n:
                continue  # sovrapposizione nello stesso file
            key = (first[0], other[0], first[1] - other[1])
            prev = last.get(key)
            last[key] = first[1]
            if prev is not None and 0 < first[1] - prev <= n:
                continue  # stesso blocco duplicato, già segnalato
            if (key, first[1]) in seen:
                continue
            seen.add((key, first[1]))
            la = norm[first[0]][first[1]][0]
            lb = norm[other[0]][other[1]][0]
            out.append(Finding("duplicate_code", sev, other[0], lb,
                               f"blocco di almeno {n} righe uguale a {first[0]}:{la}. Estrai la logica comune "
                               "(libs/utils per trasformazioni pure, model/<Tabella> per l'accesso ai dati) e riusala."))
    return sorted(out, key=lambda f: (f.path, f.line))
